# =============================================================================
# Say モジュール — 吹き出し（Speech Bubble）プラグインの名前空間
# =============================================================================
#
# 吹き出しプラグインのレジストリと、色ユーティリティと、共通機能を提供するのだ～🌱
# Liquid タグの実装は say.rb へ、各キャラクターの Provider は個別のファイルへ分けてあるのだ～🌱
#
module Say

  # ===========================================================================
  # キャラクターレジストリ
  # ===========================================================================

  # 登録済みキャラクターのハッシュなのだ～🌱
  # キャラ名（String）がキーで、Provider インスタンスが値なのだ～🌱
  # 直接触らずに、register_character メソッドを通して登録してほしいのだ～🌱
  CHARACTERS = {}

  # キャラクターを登録するのだ～🌱
  # 各 Provider ファイルのトップレベルから呼び出すことを想定しているのだ～🌱
  #
  # 使用例:
  #   Say.register_character("empty", Say::EmptyProvider.new)
  #
  def self.register_character(name, provider)
    CHARACTERS[name] = provider
  end

  # ===========================================================================
  # 色ユーティリティ
  # ===========================================================================

  # 16進数カラーコード文字列を [R, G, B] の整数配列へパースするのだ～🌱
  # "#rgb" の3桁短縮形と "#rrggbb" の6桁形式に対応しているのだ～🌱
  # "#" プレフィックスは省略できるのだ～🌱
  # パースに失敗したときは nil を返すのだ～🌱
  def self.parse_hex_color(hex)
    hex = hex.delete_prefix("#")
    case hex.length
    when 3
      # 短縮形: 各桁を2回繰り返して6桁に展開する（例: "f0a" → "ff00aa"）
      hex.chars.map { |c| (c * 2).to_i(16) }
    when 6
      # 完全形は、2桁ずつ区切って変換するのだ～🌱
      hex.scan(/../).map { |c| c.to_i(16) }
    else
      nil
    end
  end

  # R, G, B の整数値（各 0～255）を "#rrggbb" 形式の文字列へ変換するのだ～🌱
  # 範囲外の値は 0～255 にクランプされるのだ～🌱
  def self.rgb_to_hex(r, g, b)
    "#%02x%02x%02x" % [r.clamp(0, 255), g.clamp(0, 255), b.clamp(0, 255)]
  end

  # R, G, B の整数値から、W3C の定義に基づく相対輝度（0.0～1.0）を計算するのだ～🌱
  # sRGB のガンマ補正を踏まえた線形化をしてから、輝度係数で重み付けするのだ～🌱
  def self.relative_luminance(r, g, b)
    [r, g, b]
      .map { |c| c / 255.0 }
      .map { |c| c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055)**2.4 }
      .then { |rs, gs, bs| 0.2126 * rs + 0.7152 * gs + 0.0722 * bs }
  end

  # 塗りつぶし色から、視認性の良い枠線色を自動で導き出すのだ～🌱
  # 明るい色（相対輝度 > 0.5）には暗い枠線を、暗い色には明るい枠線を生成するのだ～🌱
  # パースに失敗したときは中間グレー "#888888" を返すのだ～🌱
  def self.derive_border_color(fill_hex)
    rgb = parse_hex_color(fill_hex)
    return "#888888" unless rgb

    lum = relative_luminance(*rgb)
    if lum > 0.5
      # 明るい塗りのときは、各チャンネルを60%に暗くするのだ～🌱
      rgb_to_hex(*rgb.map { |c| (c * 0.6).round })
    else
      # 暗い塗りのときは、各チャンネルを白方向に40%明るくするのだ～🌱
      rgb_to_hex(*rgb.map { |c| (c + (255 - c) * 0.4).round })
    end
  end
end
