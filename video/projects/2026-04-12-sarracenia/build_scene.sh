#!/usr/bin/env bash
# =============================================================================
# build_scene.sh — サラセニア寸劇の「構成」を組み立てるのだ～🌱（動画タイトルのディレクトリの入口なのだ～🌱）
# -----------------------------------------------------------------------------
# このディレクトリ（projects/2026-04-12-sarracenia/）は、汎用レンダラー（../../renderer/）にも、雑多パート（../../）にも
# 依存しない、自己完結したパートなのだ～🌱役割は「タイムラインを受け取って、レンダラーに渡す材料
# （assets.js・立ち絵 portrait/・構成jsonl frames.jsonl）をぜんぶ作る」ことなのだ～🌱
#
# このスクリプトは、このディレクトリへ cd してから、同じディレクトリの build_scene.xa1 を呼ぶだけなのだ～🌱
# 処理の中身と、出力の一覧は、build_scene.xa1 にあるのだ～🌱
#
# 入力：
#   $1 … timeline.json のパス（省略時は ../../timeline.json）なのだ～🌱 尺・台詞区間・シーン・アイテムが入っているのだ～🌱
#        ※ タイムラインの作り手（音声合成・結合）は雑多パートの担当で、ここはその結果を受け取るだけなのだ～🌱
#
# 前提：外部取得リソースを ../common/resources/ の所定パスに置くのだ～🌱（*.md5 が置き場所と中身を示すのだ～🌱）
# =============================================================================
set -euo pipefail
cd "$(dirname "$0")"   # projects/2026-04-12-sarracenia/

# リポジトリ同梱の xarpite（相対パス）で build_scene.xa1 を実行するのだ～🌱
../../../xarpite/xarpite -A 5 -q -f build_scene.xa1 "$@"
